// Run through playwright-cli run-code --filename after opening the local frontend.
async (page) => {
  const qa = { requests: [], errors: [] };
  page.__newChatQA = qa;
  page.on('request', (r) => { if (new URL(r.url()).pathname.startsWith('/api/')) qa.requests.push({ method: r.method(), path: new URL(r.url()).pathname, body: r.postDataJSON() }); });
  page.on('pageerror', (e) => qa.errors.push(e.message));
  const check = (ok, message) => { if (!ok) throw new Error(message) };
  const nav = page.getByRole('navigation', { name: '工作区栏位' });
  const selectPane = async (name) => { if (await nav.isVisible()) await nav.getByRole('button', { name, exact: true }).click(); };
  const read = async (id) => {
    await selectPane('草稿');
    await page.getByRole('textbox', { name: '按草稿编号读取', exact: true }).fill(id);
    const response = page.waitForResponse((r) => r.request().method() === 'GET' && r.url().endsWith(`/api/drafts/${id}`));
    await page.getByRole('button', { name: '读取草稿', exact: true }).click();
    const result = await response;
    check(result.status() === 200, 'Read failed');
    await page.getByRole('textbox', { name: '新草稿生成要求', exact: true }).waitFor({ state: 'visible' });
    return result.json();
  };
  const checkFocus = async () => {
    const title = page.getByRole('textbox', { name: '资料 1 标题', exact: true });
    await title.waitFor({ state: 'visible' });
    check(await title.evaluate((el) => el === document.activeElement), 'New draft did not focus the first source title');
    check(await title.inputValue() === '', 'New draft is not blank');
    check(!new URL(page.url()).searchParams.has('draftId'), 'New form retains an old draft ID');
  };
  const composerFits = async () => {
    const box = await page.getByRole('textbox', { name: '新草稿生成要求', exact: true }).boundingBox();
    const button = await page.getByRole('button', { name: '按新要求生成新草稿', exact: true }).boundingBox();
    const viewport = page.viewportSize();
    check(box && button && box.y >= 0 && button.y + button.height <= viewport.height && box.x >= 0 && button.x + button.width <= viewport.width, 'Composer is outside viewport');
  };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '01 杨家埠木版年画 两份独立资料 · 保留原文与链接', exact: true }).click();
  const created = page.waitForResponse((r) => r.request().method() === 'POST' && r.url().endsWith('/api/drafts'));
  await page.getByRole('button', { name: '生成文案并核对依据 Ctrl ↵', exact: true }).click();
  const draft = await (await created).json();
  await page.getByRole('button', { name: '查看原文依据', exact: true }).waitFor();
  await page.getByRole('button', { name: '＋ 新建', exact: true }).click();
  await checkFocus();
  for (const width of [1440, 900, 390]) {
    await page.setViewportSize({ width, height: width === 390 ? 844 : 1000 });
    await read(draft.draftId);
    await composerFits();
    await page.getByRole('button', { name: '在右栏编辑', exact: true }).click();
    const editor = page.getByRole('textbox', { name: '第 2 段正文编辑', exact: true });
    const unsaved = `未保存修改，窗口宽度 ${width}`;
    await editor.fill(unsaved);
    await selectPane('草稿');
    await page.getByRole('button', { name: '＋ 新建', exact: true }).click();
    await page.getByRole('dialog', { name: '开始新草稿？' }).getByRole('button', { name: '取消', exact: true }).click();
    check(new URL(page.url()).searchParams.get('draftId') === draft.draftId, 'Cancel changed the draft');
    await selectPane('文件');
    check(await editor.inputValue() === unsaved, 'Cancel discarded edits');
    await selectPane('正文');
    await composerFits();
    await selectPane('草稿');
    await page.getByRole('button', { name: '＋ 新建', exact: true }).click();
    await page.getByRole('dialog', { name: '开始新草稿？' }).getByRole('button', { name: '确认', exact: true }).click();
    await checkFocus();
    await page.screenshot({ path: `output/playwright/new-chat-new-${width}.png`, scale: 'css', animations: 'disabled' });
  }
  const restored = await read(draft.draftId);
  check(JSON.stringify(restored) === JSON.stringify(draft), 'New draft action changed saved original');
  const instruction = '压缩为更简短的工艺介绍，不添加票价。';
  const input = page.getByRole('textbox', { name: '新草稿生成要求', exact: true });
  await input.fill(instruction);
  await page.route('**/api/drafts', (route) => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ detail: { message: '验收模拟创建失败' } }) }), { times: 1 });
  await page.getByRole('button', { name: '按新要求生成新草稿', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '原稿未更改，输入已保留' }).waitFor();
  check(await input.inputValue() === instruction, 'Failed request lost user input');
  check(new URL(page.url()).searchParams.get('draftId') === draft.draftId, 'Failed request replaced original');
  await page.screenshot({ path: 'output/playwright/new-chat-failed-request.png', scale: 'css', animations: 'disabled' });
  await page.route('**/api/drafts', async (route) => { await new Promise((resolve) => setTimeout(resolve, 700)); await route.continue(); }, { times: 1 });
  const beforePosts = page.__newChatQA.requests.filter((r) => r.method === 'POST').length;
  const response = page.waitForResponse((r) => r.request().method() === 'POST' && r.url().endsWith('/api/drafts'));
  await page.getByRole('button', { name: '按新要求生成新草稿', exact: true }).click();
  check(await input.isDisabled(), 'Input not locked while request is pending');
  check(await page.getByRole('button', { name: '正在生成新草稿…', exact: true }).isDisabled(), 'Submit not locked');
  await page.keyboard.press('Enter');
  const newResponse = await response;
  check(newResponse.status() === 201, 'New draft request failed');
  const next = await newResponse.json();
  check(next.draftId !== draft.draftId && next.mode === 'mock', 'Not a separate mock draft');
  check(JSON.stringify(next.sources) === JSON.stringify(draft.sources), 'Original source attribution changed');
  check(next.brief.includes(draft.brief) && next.brief.endsWith(instruction), 'Requirements were not combined');
  check(page.__newChatQA.requests.filter((r) => r.method === 'POST').length === beforePosts + 1, 'Duplicate POST');
  await page.getByText(`已按新要求生成新草稿；原稿 ${draft.draftId} 保留，可在左栏或按编号重新打开。`, { exact: true }).waitFor();
  check(await input.inputValue() === '', 'Successful submission did not clear input');
  await composerFits();
  await page.screenshot({ path: 'output/playwright/new-chat-composer-narrow.png', scale: 'css', animations: 'disabled' });
  check(JSON.stringify(await read(draft.draftId)) === JSON.stringify(draft), 'Original draft was overwritten');
  await read(next.draftId);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: '查看原文依据', exact: true }).click();
  check(await page.locator('.drawer mark').textContent() === next.blocks[0].evidence[0].quote, 'Evidence is missing');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '在右栏编辑', exact: true }).click();
  const newText = '走近杨家埠木版年画，体验安排请提前向官方核实。';
  await page.getByRole('textbox', { name: '第 2 段正文编辑', exact: true }).fill('长文可见性验收。'.repeat(100));
  await composerFits();
  const scroll = await page.locator('.chat-scroll').evaluate((el) => ({ scrollable: el.scrollHeight > el.clientHeight, pageHeight: document.documentElement.scrollHeight, viewportHeight: innerHeight }));
  check(scroll.scrollable && scroll.pageHeight <= scroll.viewportHeight, 'Long copy scrolls the page instead of the message area');
  await page.locator('.chat-scroll').hover();
  await page.mouse.wheel(0, 2000);
  await composerFits();
  await page.screenshot({ path: 'output/playwright/new-chat-long-copy.png', scale: 'css', animations: 'disabled' });
  await page.getByRole('textbox', { name: '第 2 段正文编辑', exact: true }).fill(newText);
  const saving = page.waitForResponse((r) => r.request().method() === 'PATCH');
  await page.locator('.col-right').getByRole('button', { name: '保存草稿', exact: true }).click();
  const saved = await (await saving).json();
  check(saved.blocks[1].status === 'edited_needs_review', 'Edited status missing');
  check(JSON.stringify(saved.blocks[0]) === JSON.stringify(next.blocks[0]), 'Unchanged evidence changed');
  await page.getByRole('button', { name: '导出', exact: true }).click();
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: '.txt 下载服务端 TXT 来自数据库最后保存的正文与状态标记', exact: true }).click();
  const file = await downloading;
  await file.saveAs('output/playwright/new-chat-regression.txt');
  const decoder = new TextDecoder();
  let content = '';
  for await (const chunk of await file.createReadStream()) content += decoder.decode(chunk, { stream: true });
  content += decoder.decode();
  check(content.includes(newText) && !content.includes(next.blocks[1].text), 'Download contains wrong version');
  check(content.includes('人工修改后待复核'), 'Download lacks review marker');
  await page.getByRole('button', { name: '查看原文依据', exact: true }).click();
  check(await page.locator('.drawer mark').textContent() === next.blocks[0].evidence[0].quote, 'Saved evidence is missing');
  await page.getByRole('button', { name: '关闭', exact: true }).click();
  await composerFits();
  await page.screenshot({ path: 'output/playwright/new-chat-final-desktop.png', scale: 'css', animations: 'disabled' });
  check(page.__newChatQA.errors.length === 0, JSON.stringify(page.__newChatQA.errors));
  check(!page.__newChatQA.requests.some((r) => /refine|chat/.test(r.path)), 'Called an unsupported chat endpoint');
  return { newDraftFocused: true, cancelPreservesEdits: true, failurePreservesDraftAndInput: true, noDuplicatePost: true,
    originalDraftId: draft.draftId, newDraftId: next.draftId, sourceCount: next.sources.length, mode: next.mode,
    savedStatus: saved.blocks[1].status, download: file.suggestedFilename(), pageErrors: page.__newChatQA.errors };
}
